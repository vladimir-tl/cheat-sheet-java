package org.tl.theory.ru;

/**
 * ТЕОРИЯ: цикл while
 *
 * Короткие примеры. Скопируйте любой из них в метод main и запустите.
 *
 * Содержание
 *
 * Основы
 *   1. Синтаксис: while (condition)
 *   2. while или for?
 *   3. Хотя бы один раз: do-while
 *
 * Управление циклом
 *   4. break и continue
 *   5. Бесконечный цикл
 *
 * Практика: см. org.tl.loops.whileloop (WhileCheatSheet, WhileTasks, WhileSolutions).
 */
public class WhileTheory {

    /**
     * 1. Синтаксис: while (condition)
     *
     * while повторяет тело, пока условие истинно. Условие проверяется ПЕРЕД каждой
     * итерацией, поэтому тело может не выполниться ни разу: если условие ложно с самого
     * начала, ничего не происходит.
     *
     * Порядок: условие -> тело -> условие -> тело ... -> условие false -> выход.
     *
     * Счётчик живёт снаружи цикла, и менять его в теле нужно ВАМ.
     * Если ничего в теле не влияет на условие, цикл никогда не закончится.
     */
    static void syntax() {
        // Вывести 0 1 2 3 4:
        int i = 0;
        while (i < 5) {
            System.out.println(i);
            i++; // без этой строки: бесконечный цикл
        }

        // Условие ложно с самого начала -> тело не выполняется ни разу:
        int x = 10;
        while (x < 5) {
            System.out.println(x); // не выполняется
        }
    }

    /**
     * 2. while или for?
     *
     * for: число повторений известно или нужен счётчик.
     * while: число повторений заранее неизвестно; повторяете, пока что-то не произойдёт.
     */
    static void whileOrFor() {
        // Известно: ровно 5 раз -> for
        for (int i = 0; i < 5; i++) {
            System.out.println(i);
        }

        // Неизвестно: сколько цифр в числе? Столько шагов, сколько понадобится.
        int number = 12345;
        int digits = 0;
        while (number > 0) {
            number /= 10; // отбросить последнюю цифру: 1234, 123, 12, 1, 0
            digits++;
        }
        System.out.println(digits); // 5
    }

    /**
     * 3. Хотя бы один раз: do-while
     *
     * В do-while условие проверяется ПОСЛЕ тела, поэтому тело выполняется минимум один раз.
     * Обратите внимание на точку с запятой после закрывающей скобки.
     */
    static void doWhile() {
        int x = 10;

        // x < 5 ложно, но тело всё равно выполнится один раз -> напечатает 10:
        do {
            System.out.println(x);
        } while (x < 5);

        // То же условие с обычным while ничего не напечатает:
        while (x < 5) {
            System.out.println(x);
        }
    }

    /**
     * 4. break и continue
     *
     * break полностью выходит из цикла. continue сразу переходит к следующей проверке условия.
     */
    static void breakAndContinue() {
        // break: остановиться на 6 -> 1 2 3 4 5
        int i = 0;
        while (i < 10) {
            i++;
            if (i == 6) break;
            System.out.println(i);
        }

        // Ловушка: continue ДО обновления. i не меняется, цикл никогда не закончится:
        // int j = 0;
        // while (j < 10) {
        //     if (j == 3) continue; // j навсегда остаётся 3
        //     j++;
        // }
        // Обновляйте счётчик до continue.
    }

    /**
     * 5. Бесконечный цикл
     *
     * while (true) это нормальный способ сказать «повторяй, пока я не скажу стоп».
     * Выходите из него через break или return.
     */
    static void infinite() {
        int n = 0;
        while (true) {
            n++;
            if (n > 3) break;
        }

        // Ловушка: точка с запятой после while это ПУСТОЕ тело. Цикл крутится вечно:
        // int i = 0;
        // while (i < 5); { i++; }
    }
}
