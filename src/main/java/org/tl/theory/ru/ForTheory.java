package org.tl.theory.ru;

/**
 * ТЕОРИЯ: цикл for
 *
 * Короткие примеры. Скопируйте любой из них в метод main и запустите.
 *
 * Содержание
 *
 * Основы
 *   1. Синтаксис и порядок выполнения: for (init; condition; update)
 *   2. Счёт вверх, вниз и с шагом
 *   3. Вложенные циклы
 *
 * Управление циклом
 *   4. break и continue
 *   5. Бесконечный цикл
 *
 * Обход данных
 *   6. Массив по индексу
 *   7. for-each
 *
 * Практика: см. org.tl.loops.forloop (ForCheatSheet, ForTasks, ForSolutions).
 */
public class ForTheory {

    /**
     * 1. Синтаксис и порядок выполнения: for (init; condition; update)
     *
     * Цикл повторяет блок кода. Используйте for, когда заранее известно, сколько раз
     * повторять, или когда нужен счётчик.
     *
     * В заголовке три части, все необязательные, разделены символом ;
     *   - init: выполняется один раз, обычно объявляет счётчик (int i = 0)
     *   - condition: проверяется перед каждой итерацией; когда он false, цикл заканчивается
     *   - update: выполняется после каждой итерации, обычно меняет счётчик (i++)
     *
     * Порядок: init -> condition -> тело -> update -> condition -> тело -> update ... -> condition false -> выход.
     */
    static void syntax() {
        // Вывести 0 1 2 3 4:
        for (int i = 0; i < 5; i++) {
            System.out.println(i);
        }

        // Счётчик существует только внутри цикла. Это не скомпилируется:
        // System.out.println(i);
    }

    /**
     * 2. Счёт вверх, вниз и с шагом
     *
     * Меняйте init, condition и update, чтобы получить любую последовательность.
     * i++ то же самое, что i += 1; i-- то же самое, что i -= 1.
     */
    static void counting() {
        // Вверх: 1 2 3 4 5
        for (int i = 1; i <= 5; i++) {
            System.out.println(i);
        }

        // Вниз: 5 4 3 2 1
        for (int i = 5; i >= 1; i--) {
            System.out.println(i);
        }

        // Шаг 2: 0 2 4 6 8 10
        for (int i = 0; i <= 10; i += 2) {
            System.out.println(i);
        }

        // < не включает конец, <= включает.
        // for (int i = 0; i < 3; i++)  -> 0 1 2   (3 итерации)
        // for (int i = 0; i <= 3; i++) -> 0 1 2 3 (4 итерации)
    }

    /**
     * 3. Вложенные циклы
     *
     * Цикл внутри цикла. Внутренний цикл выполняется полностью на каждую итерацию внешнего:
     * 3 x 3 итерации = 9 запусков тела.
     */
    static void nested() {
        // Таблица умножения 3 x 3:
        for (int i = 1; i <= 3; i++) {
            for (int j = 1; j <= 3; j++) {
                System.out.print(i * j + "\t");
            }
            System.out.println(); // перевод строки после каждой строки таблицы
        }
        // 1  2  3
        // 2  4  6
        // 3  6  9
    }

    /**
     * 4. break и continue
     *
     * break полностью выходит из цикла. continue пропускает остаток текущей итерации
     * и переходит к части update.
     */
    static void breakAndContinue() {
        // continue: пропустить 3 -> 0 1 2 4 5 6 7 8 9
        for (int i = 0; i < 10; i++) {
            if (i == 3) continue;
            System.out.println(i);
        }

        // break: остановиться на 6 -> 0 1 2 3 4 5
        for (int i = 0; i < 10; i++) {
            if (i == 6) break;
            System.out.println(i);
        }

        // Во вложенных циклах break выходит только из ВНУТРЕННЕГО цикла.
    }

    /**
     * 5. Бесконечный цикл
     *
     * Все три части заголовка необязательны. Без условия цикл сам никогда не остановится:
     * выходите из него через break или return.
     */
    static void infinite() {
        int n = 0;
        for (;;) {
            n++;
            if (n > 3) break;
        }

        // Ловушка: условие, которое по ошибке всегда истинно
        // for (int i = 0; i >= 0; i++) { ... } // i никогда не станет отрицательным (до переполнения)
    }

    /**
     * 6. Массив по индексу
     *
     * Используйте индекс, когда нужна позиция или нужно менять элементы.
     * У массива длины n индексы 0 .. n-1. Длина массива это arr.length (без скобок).
     */
    static void arrayByIndex() {
        int[] arr = {10, 20, 30};

        // Вывести каждый элемент:
        for (int i = 0; i < arr.length; i++) {
            System.out.println(arr[i]);
        }

        // Удвоить каждый элемент (меняет массив):
        for (int i = 0; i < arr.length; i++) {
            arr[i] = arr[i] * 2; // {20, 40, 60}
        }

        // Ловушка: <= вместо <. В массиве 3 элемента, индекса 3 не существует:
        // for (int i = 0; i <= arr.length; i++) { arr[i] }
        // -> ArrayIndexOutOfBoundsException: Index 3 out of bounds for length 3
    }

    /**
     * 7. for-each
     *
     * for (Type x : collection) берёт элементы по одному. Короче, и нет индекса,
     * в котором можно ошибиться. Используйте, когда элементы только читаются.
     */
    static void forEach() {
        int[] arr = {10, 20, 30};

        for (int x : arr) {
            System.out.println(x);
        }

        // x это КОПИЯ элемента. Изменение x не меняет массив:
        for (int x : arr) {
            x = x * 2; // arr по-прежнему {10, 20, 30}
        }

        // Нужен индекс или нужно менять элементы -> цикл по индексу (см. 6).
        // Для List работает так же: см. ListTheory.
    }

    // Ловушка: точка с запятой после заголовка for это ПУСТОЕ тело.
    // Блок ниже не относится к циклу и выполняется один раз:
    //
    //   for (int i = 0; i < 5; i++);
    //   {
    //       System.out.println("hello"); // напечатается один раз, а не 5
    //   }
}
