package org.tl.theory.ru;

/**
 * ТЕОРИЯ: разминка, приёмы для первых задач в стиле LeetCode
 *
 * Короткие примеры. Скопируйте любой из них в метод main и запустите.
 *
 * Содержание
 *
 * Массивы
 *   1. Проход: один цикл и ответ «на сейчас»
 *   2. Два указателя: с обоих концов к середине
 *   3. Указатель записи: пишем в тот же массив
 *
 * Числа и символы
 *   4. Цифры и символы: % 10, / 10 и разница символов
 *
 * Ловушки
 *   5. Проверка на null и крайние случаи
 *   6. Переполнение int
 *
 * Практика: см. org.tl.warmup (WarmupCheatSheet, WarmupTasks, WarmupSolutions).
 */
public class WarmupTheory {

    /**
     * 1. Проход: один цикл и ответ «на сейчас»
     *
     * Большинство простых задач это один цикл по массиву и переменная, в которой лежит
     * ответ на данный момент: сумма, счётчик, «нашли или нет».
     *
     * Подумайте, с какого значения начать переменную и что должно произойти с пустым массивом.
     */
    static void scan() {
        int[] numbers = {4, 9, 2, 8, 6};
        int evenCount = 0;                     // ответ на данный момент
        for (int x : numbers) {
            if (x % 2 == 0) {
                evenCount++;
            }
        }
        System.out.println(evenCount);         // 4
    }

    /**
     * 2. Два указателя: с обоих концов к середине
     *
     * Два указателя: один индекс в начале (left), другой в конце (right).
     * Сделайте что-то с обоими, двигайте их навстречу друг другу, остановитесь, когда они встретятся.
     * Так обрабатывают пары с двух концов.
     */
    static void twoPointers() {
        int[] numbers = {1, 2, 3, 4, 5, 6};
        int left = 0;
        int right = numbers.length - 1;
        while (left < right) {
            System.out.println(numbers[left] + numbers[right]);   // 7, 7, 7
            left++;
            right--;
        }
    }

    /**
     * 3. Указатель записи: пишем в тот же массив
     *
     * Иногда результат нужно складывать в сам массив, не создавая второй. Заведите индекс pos:
     * место для следующего подходящего элемента. Читайте циклом, пишите через pos.
     * Здесь: чётные числа собираются в начале массива.
     */
    static void writePointer() {
        int[] numbers = {3, 8, 5, 6, 1};
        int pos = 0;                           // место для следующего чётного числа
        for (int x : numbers) {
            if (x % 2 == 0) {
                numbers[pos] = x;
                pos++;
            }
        }
        // первые pos ячеек теперь хранят чётные числа: [8, 6, ...]
        System.out.println(pos);               // 2
    }

    /**
     * 4. Цифры и символы: % 10, / 10 и разница символов
     *
     * n % 10 это последняя цифра числа n, n / 10 отрезает её.
     *
     * char это число: 'a' равен 97, 'b' равен 98 и так далее. Буквы идут подряд,
     * поэтому разница символов показывает расстояние между ними.
     */
    static void digitsAndChars() {
        int n = 4072;
        System.out.println(n % 10);            // 2: последняя цифра
        System.out.println(n / 10);            // 407: without последняя цифра
        System.out.println('d' - 'a');         // 3: номер буквы в алфавите
    }

    /**
     * 5. Проверка на null и крайние случаи
     *
     * Перед использованием значения, которое может быть null, проверьте его. Вызов метода у null
     * бросает NullPointerException. && останавливается на первом false, поэтому проверка идёт первой.
     *
     * Пробуйте каждую задачу с: пустым массивом, одним элементом, одинаковыми элементами, нулём, отрицательным числом.
     */
    static void nullGuard() {
        String name = null;
        String shown = name == null ? "guest" : name;
        System.out.println(shown);                          // guest
        boolean longName = name != null && name.length() > 3;
        System.out.println(longName);                       // false: name.length() is не вызывается
    }

    /**
     * 6. Переполнение int
     *
     * int считается в int. Если результат не помещается (максимум около 2,1 миллиарда),
     * число молча «заворачивается» в неверное. Чтобы получить точный результат, используют long;
     * Math.addExact и подобные методы вместо неверного числа бросают исключение.
     */
    static void overflow() {
        int max = Integer.MAX_VALUE;           // 2147483647
        System.out.println(max + 1);           // -2147483648: заворачивается, ошибки нет
        System.out.println((long) max + 1);    // 2147483648
        // Math.addExact(max, 1) бросило бы ArithmeticException вместо неверного числа
    }
}
