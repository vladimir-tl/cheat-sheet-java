    /**
     * 1. Что такое Map
     *
     * Map хранит данные парами: «ключ -> значение». Сначала посмотрим на примеры таких пар:
     *
     *   "Anna"  -> 3000        имя сотрудника -> зарплата
     *   "apple" -> "яблоко"    слово -> перевод
     *   "EE"    -> "Estonia"   код страны -> название страны
     *
     * Ключ — то, по чему мы ищем: имя, слово, код. Значение — то, что хотим найти по этому
     * ключу: зарплату, перевод, название. Похоже на словарь: вы ищете слово «apple»
     * и сразу видите рядом перевод. Листать весь словарь подряд не нужно,
     * поэтому поиск по ключу в Map быстрый.
     *
     * Зачем нужен Map, если есть List? Представим, что нужно узнать зарплату Анны.
     * В List мы бы хранили сотрудников по порядку и искали Анну циклом: первый не она,
     * второй не она, и так до конца. Чем длиннее список, тем дольше поиск. Map отдаёт
     * значение сразу по ключу: salaries.get("Anna"). Сотрудников может быть десять
     * или миллион, а поиск по ключу всё равно быстрый. И код получается короче:
     * одна строка вместо цикла с проверкой.
     *
     * Два важных правила:
     * - Ключи не повторяются. Второго ключа "Anna" в Map быть не может. Если положить значение
     *   под ключ, который уже есть, старое значение заменится новым (подробнее в разделе 2).
     * - Значения повторяться могут. У "Anna" и у "Bob" вполне может быть одинаковая зарплата 3000.
     *
     * При создании Map в угловых скобках указывают два типа: сначала тип ключа, потом тип
     * значения. Запись Map<String, Integer> значит «ключи — строки, значения — целые числа».
     * Примитивы вроде int сюда писать нельзя, нужны классы-обёртки: Map<String, Integer>,
     * а не Map<String, int> (см. PrimitivesAndWrappersTheory).
     *
     * Map — не List. У него нет индексов 0, 1, 2, и «первого элемента» тоже нет.
     * Поэтому map.get(0) не вернёт первую пару: Map поищет ключ 0, не найдёт его и вернёт null.
     *
     * Как выбрать между ними? Берите Map, когда в задаче есть «по чему искать»:
     * - Поиск по ключу: зарплата по имени, товар по артикулу, страна по коду.
     * - Подсчёт: сколько раз встречается каждое слово, например «кот» -> 3.
     * - Группировка: отдел -> список его сотрудников.
     * - Уникальность: один логин — один пользователь, второго такого же ключа не будет.
     *
     * Берите List, когда ключ не нужен:
     * - Порядок и номер: нужен первый, второй или последний элемент.
     * - Простой перебор: значения нужно только пройти циклом, искать среди них не нужно.
     * - Повторы: одинаковые элементы — это нормально, как в списке покупок.
     *
     * Для любопытных: технически Map — отдельный интерфейс, и он НЕ наследует Collection
     * (а List и Set наследуют). Поэтому у Map нет метода add(x), вместо него put(key, value).
     * И пройти по Map циклом for-each напрямую тоже не получится, для этого есть entrySet,
     * keySet и values (см. раздел 6).
     *
     * Ниже первый пример из списка в коде: имена сотрудников и их зарплаты.
     */
    static void whatIsMap() {
        // Employee name -> salary:
        //   "Anna" -> 3000
        //   "Bob"  -> 2500
        Map<String, Integer> salaries = new HashMap<>();
        salaries.put("Anna", 3000);
        salaries.put("Bob", 2500);
    }

    /**
     * 2. Положить и получить: put и get
     *
     * Чтобы положить пару в Map, вызовите put(key, value): сначала ключ, потом значение.
     * Чтобы достать значение, вызовите get(key) и передайте ключ. Map вернёт то, что лежит
     * под этим ключом.
     *
     * Если вызвать put с ключом, который уже есть, новая пара не появится. Map заменит старое
     * значение новым, а размер останется прежним. Ошибки при этом не будет, так что старое
     * значение пропадёт молча.
     *
     * Посмотрим на примере: сначала Анне 25, потом мы записываем ей 26.
     */
    static void putAndGet() {
        Map<String, Integer> ages = new HashMap<>();

        ages.put("Anna", 25);   // {Anna=25}
        ages.put("Bob", 30);    // {Anna=25, Bob=30}
        ages.put("Anna", 26);   // тот же ключ -> {Anna=26, Bob=30}

        ages.get("Anna");       // 26
        ages.size();            // 2: по-прежнему два ключа
    }

    /**
     * 3. Нет ключа: null и getOrDefault
     *
     * Что будет, если спросить ключ, которого в Map нет? Ошибки не будет: get просто вернёт null,
     * то есть «ничего».
     *
     * Ловушка: не записывайте результат get сразу в int. Строка int age = ages.get("Zed")
     * упадёт с NullPointerException. get вернул null, а null нельзя превратить в число int.
     * Сохраняйте результат в Integer или берите getOrDefault (см. PrimitivesAndWrappersTheory).
     *
     * Чтобы не возиться с null, есть getOrDefault(key, x). Он принимает два аргумента:
     * ключ и запасное значение. Дальше всё просто:
     * - Ключ есть: метод вернёт значение из Map, а запасное x не понадобится.
     * - Ключа нет: метод вернёт x.
     *
     * Например, в ages лежит только "Anna" -> 26. Тогда getOrDefault("Anna", 0) вернёт 26,
     * а getOrDefault("Zed", 0) вернёт 0.
     *
     * Запасное значение выбирайте под задачу. Это ответ, который разумно дать, когда данных нет:
     * 0 для количества или суммы, "" для текста, -1 как пометка «не найдено». Тип x должен
     * совпадать с типом значений. Для Map<String, Integer> подойдёт 0, а строка "нет"
     * не скомпилируется.
     *
     * Важно: getOrDefault ничего не кладёт в Map, он только читает. После
     * getOrDefault("Zed", 0) ключа "Zed" в Map по-прежнему нет, и size() не меняется.
     * Если пару нужно сохранить, вызовите put.
     *
     * Чаще всего getOrDefault нужен для подсчёта. Допустим, мы считаем, сколько раз
     * встречается каждое слово. Для каждого слова берём текущий счётчик через
     * getOrDefault(word, 0) и кладём обратно счётчик + 1. Когда слово встретилось впервые,
     * его ещё нет в Map, и метод вернёт 0. Получится 0 + 1 = 1. Без getOrDefault пришлось бы
     * отдельно проверять, есть ли слово, через containsKey или сравнение с null.
     *
     * Тонкость для любопытных: если ключ есть, но под ним лежит null (map.put("Zed", null)),
     * getOrDefault вернёт null, а не x. Запасное значение подставляется, только когда ключа
     * нет совсем. В обычных задачах null в Map не кладут, так что это редкость.
     */
    static void missingKey() {
        Map<String, Integer> ages = new HashMap<>();
        ages.put("Anna", 26);

        // get: ключа нет -> null
        Integer unknown = ages.get("Zed");        // null
        // int crash = ages.get("Zed");           // NullPointerException

        // getOrDefault: ключ есть -> его значение, ключа нет -> запасное
        ages.getOrDefault("Anna", 0);             // 26: ключ есть, 0 не понадобился
        ages.getOrDefault("Zed", 0);              // 0: ключа нет
        ages.size();                              // 1: "Zed" в Map НЕ добавился

        // Подсчёт: сколько раз встречается каждое слово
        String[] words = {"cat", "dog", "cat"};
        Map<String, Integer> counts = new HashMap<>();
        for (String word : words) {
            counts.put(word, counts.getOrDefault(word, 0) + 1);
        }
        // counts: cat -> 2, dog -> 1
    }

    /**
     * 4. Проверка ключа: containsKey
     *
     * Иногда нужно просто узнать, есть ли ключ в Map. Для этого есть containsKey(key):
     * он вернёт true, если ключ есть, и false, если нет. Работает так же быстро, как get.
     *
     * Похожий метод containsValue(value) ищет среди значений. Он медленный: быстро искать
     * Map умеет только по ключам, поэтому здесь перебирает все пары подряд. На большой Map
     * это заметно.
     */
    static void contains() {
        Map<String, Integer> ages = new HashMap<>();
        ages.put("Anna", 26);

        ages.containsKey("Anna");   // true
        ages.containsKey("Zed");    // false
        ages.containsValue(26);     // true
    }

    /**
     * 5. HashMap, LinkedHashMap, TreeMap
     *
     * В Java есть несколько готовых видов Map. Методы у них одинаковые: put, get, containsKey
     * и остальные. Отличаются они порядком, в котором хранят пары и выводят их при печати
     * или переборе.
     *
     * Три самых частых вида:
     * - HashMap: порядок пар не гарантирован, они могут вывестись в любом порядке. Зато это
     *   самый быстрый вариант, поэтому берите его по умолчанию.
     * - LinkedHashMap: помнит порядок добавления. Какую пару положили первой, та первой
     *   и выведется.
     * - TreeMap: сортирует пары по ключу. Строки идут по алфавиту, числа от меньшего к большему.
     *
     * Слева обычно пишут просто Map, а конкретный вид указывают справа, после new.
     * Так потом легко заменить HashMap на TreeMap: правка нужна только в одном месте.
     *
     * Есть и короткий способ создать Map сразу с данными: Map.of("Anna", 26, "Bob", 30).
     * Но такую Map нельзя изменить: любой put бросит UnsupportedOperationException.
     * Если пары нужно добавлять, создайте new HashMap<>().
     */
    static void kinds() {
        Map<String, Integer> hash = new HashMap<>();
        Map<String, Integer> linked = new LinkedHashMap<>();
        Map<String, Integer> tree = new TreeMap<>();

        // После put("Bob", 1), put("Anna", 2), put("Eve", 3):
        //   HashMap:       любой порядок
        //   LinkedHashMap: {Bob=1, Anna=2, Eve=3}
        //   TreeMap:       {Anna=2, Bob=1, Eve=3}
    }

    /**
     * 6. Перебор: entrySet, keySet, values
     *
     * Пройти по Map циклом for-each напрямую нельзя. Java не знает, что вы хотите перебрать:
     * ключи, значения или пары целиком. Поэтому сначала выберите это сами одним из трёх методов:
     * - entrySet(): пары целиком. У каждой пары есть getKey() и getValue().
     * - keySet(): только ключи.
     * - values(): только значения.
     *
     * Если в цикле нужны и ключ, и значение, берите entrySet. Тип каждой пары записывается
     * как Map.Entry<String, Integer>, то есть «запись Map с ключом String и значением Integer».
     * Выглядит длинно, но к этому быстро привыкают.
     *
     * В примере мы взяли LinkedHashMap, чтобы пары выводились в порядке добавления.
     */
    static void iterating() {
        Map<String, Integer> ages = new LinkedHashMap<>();
        ages.put("Anna", 26);
        ages.put("Bob", 30);

        // Пары: Anna=26, Bob=30
        for (Map.Entry<String, Integer> e : ages.entrySet()) {
            System.out.println(e.getKey() + "=" + e.getValue());
        }

        // Ключи: Anna, Bob
        for (String name : ages.keySet()) {
            System.out.println(name);
        }

        // Значения: 26, 30
        for (int age : ages.values()) {
            System.out.println(age);
        }
    }

    /**
     * 7. Ключи уникальны и сравниваются через equals/hashCode
     *
     * Как Map понимает, что ключ «тот же самый»? Map сравнивает ключи методами equals()
     * и hashCode(). Сначала hashCode() быстро подсказывает, где искать ключ. Потом equals()
     * проверяет, совпадает ли он на самом деле.
     *
     * У String, Integer и других стандартных классов эти методы уже написаны правильно.
     * Поэтому строки и числа — самые удобные ключи. Учтите только, что String различает
     * регистр: "Anna" и "anna" — два разных ключа.
     *
     * Со своими классами сложнее. Если в классе нет equals() и hashCode(), Java считает
     * одинаковым только один и тот же объект. Тогда два объекта с одинаковыми данными станут
     * двумя разными ключами. Проще всего сделать ключ через record: он создаёт equals()
     * и hashCode() сам.
     *
     * И ещё одна ловушка: не меняйте объект, пока он лежит в Map как ключ. Его hashCode()
     * изменится, и Map будет искать ключ не в том месте. Пара останется внутри,
     * но get её уже не найдёт.
     */
    static void keysTrap() {
        Map<String, Integer> map = new HashMap<>();
        map.put("Anna", 1);
        map.put("anna", 2);  // другой ключ: String учитывает регистр -> 2 записи
        map.size();          // 2

        // свой тип ключа: record сам даёт equals и hashCode
        record CustomerId(String email) {}
        Map<CustomerId, Integer> bonus = new HashMap<>();
        bonus.put(new CustomerId("ann@mail.ee"), 10);
        bonus.put(new CustomerId("ann@mail.ee"), 20); // тот же ключ по equals() -> значение заменено
        bonus.size();        // 1 (с обычным классом без equals было бы 2)
    }
